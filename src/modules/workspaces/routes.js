'use strict';
/**
 * Workspaces ("spaces"): invite-only rooms for study groups, lectures,
 * meetings and guided assignments. Includes shared notes, the workspace
 * assistant, meeting recordings with private-by-default audio, draft minutes
 * and live captions.
 */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { text, oneOf, id, optionalId } = require('../../lib/validate');
const { badRequest, forbidden, notFound, unavailable } = require('../../http/errors');
const prompts = require('../../ai/prompts');

const KINDS = ['meeting', 'lecture', 'discussion', 'assignment', 'study'];
const GUIDANCE = ['coach', 'socratic', 'direct', 'assessment'];
const NOTE_TYPES = ['note', 'minutes', 'task', 'resource', 'question'];
const AUDIO_TYPES = { 'audio/webm': '.webm', 'video/webm': '.webm', 'audio/mp4': '.mp4', 'audio/ogg': '.ogg', 'audio/wav': '.wav' };

/** Offline fallback when no AI is configured: rule-based extraction, clearly labelled. */
function offlineMinutes(notes) {
  const lines = notes.replace(/\r/g, '').split(/\n|(?<=[.!?])\s+/).map((x) => x.trim()).filter((x) => x.length >= 8);
  const actions = lines.filter((x) => /\b(action|todo|to-do|will|must|assigned|deadline|by (monday|tuesday|wednesday|thursday|friday|saturday|sunday)|follow.up|next step)\b/i.test(x)).slice(0, 9);
  const decisions = lines.filter((x) => /\b(decided|agreed|approved|resolved|decision|concluded)\b/i.test(x)).slice(0, 7);
  const bullets = (xs, empty) => xs.map((x) => `• ${x}`).join('\n') || `• ${empty}`;
  return [
    'DRAFT MEETING NOTES — REVIEW FOR ACCURACY',
    `KEY DISCUSSION POINTS\n${bullets(lines.slice(0, 12), 'No written notes or transcript yet.')}`,
    `POSSIBLE DECISIONS\n${bullets(decisions, 'None explicitly identified.')}`,
    `POSSIBLE ACTION ITEMS\n${bullets(actions, 'None explicitly identified.')}`,
    'Generated by a simple text extractor (no AI configured). Confirm speakers, decisions and deadlines before sharing.',
  ].join('\n\n');
}

function register(router, { db, config, access, ai, bus, audit }) {
  const isoNow = () => new Date().toISOString();
  fs.mkdirSync(config.audioDir, { recursive: true });

  const member = (user, wid) => {
    const w = access.workspaceMember(user, id(wid));
    if (!w) throw forbidden('You are not a member of this space');
    return w;
  };
  const touch = (w, what) => bus.publish(`workspace:${w.id}`, 'workspace.updated', { workspaceId: w.id, what });
  const recordingFor = (user, rid) => db.get(
    'SELECT r.* FROM meeting_recordings r JOIN workspaces w ON w.id = r.workspace_id WHERE r.id = ? AND w.institution_id = ?',
    id(rid), user.institution_id,
  );

  router.get('/api/workspaces', (ctx) => {
    const u = ctx.user;
    const rooms = db.all(
      `SELECT w.id, w.title, w.kind, w.guidance, w.instructions, w.course_id, w.creator_id, w.created, w.join_code, w.live,
              (SELECT COUNT(*) FROM workspace_members m WHERE m.workspace_id = w.id) AS member_count,
              (SELECT COUNT(*) FROM workspace_notes n WHERE n.workspace_id = w.id) AS note_count,
              (SELECT MAX(created) FROM workspace_notes n WHERE n.workspace_id = w.id) AS last_activity
       FROM workspaces w JOIN workspace_members wm ON wm.workspace_id = w.id AND wm.user_id = ?
       WHERE w.institution_id = ? AND w.archived = 0 ORDER BY COALESCE(last_activity, w.created) DESC`,
      u.id, u.institution_id,
    );
    return { rooms: rooms.map((r) => ({ ...r, live: !!r.live, isOwner: r.creator_id === u.id })), ...ai.status(u) };
  });

  router.post('/api/workspaces', async (ctx) => {
    const u = ctx.user;
    const b = await ctx.json();
    const title = text(b.title, { min: 3, max: 120, label: 'Title' });
    const kind = oneOf(b.kind, KINDS, 'Type');
    const guidance = oneOf(b.guidance || 'coach', GUIDANCE, 'Assistant approach');
    const instructions = text(b.instructions, { max: 2000, optional: true });
    const courseId = optionalId(b.course_id, 'Course');
    if (['lecture', 'assignment'].includes(kind) && !access.isStaff(u)) throw forbidden('Only lecturers or administrators can create lecture and assignment spaces');
    if (courseId && !access.teachingCourse(u, courseId)) throw forbidden('You cannot link this course');
    const code = crypto.randomBytes(5).toString('hex').toUpperCase();
    const wid = db.insert(
      'INSERT INTO workspaces(institution_id, creator_id, title, kind, course_id, join_code, guidance, instructions, created) VALUES(?, ?, ?, ?, ?, ?, ?, ?, ?)',
      u.institution_id, u.id, title, kind, courseId, code, guidance, instructions, isoNow(),
    );
    db.run('INSERT INTO workspace_members(workspace_id, user_id, joined) VALUES(?, ?, ?)', wid, u.id, isoNow());
    ctx.status = 201;
    return { id: wid, joinCode: code };
  });

  router.post('/api/workspaces/join', async (ctx) => {
    const b = await ctx.json();
    const code = text(b.code, { min: 4, max: 25, label: 'Join code' }).toUpperCase().replace(/\s/g, '');
    const w = db.get('SELECT * FROM workspaces WHERE join_code = ? AND institution_id = ? AND archived = 0', code, ctx.user.institution_id);
    if (!w) throw notFound('No space found for that code at your university');
    db.run('INSERT OR IGNORE INTO workspace_members(workspace_id, user_id, joined) VALUES(?, ?, ?)', w.id, ctx.user.id, isoNow());
    touch(w, 'members');
    return { id: w.id };
  });

  router.get('/api/workspaces/:id', (ctx) => {
    const u = ctx.user;
    const w = member(u, ctx.params.id);
    const notes = db.all('SELECT n.id, n.category, n.content, n.created, n.author_id, u.name AS author FROM workspace_notes n JOIN users u ON u.id = n.author_id WHERE n.workspace_id = ? ORDER BY n.id DESC LIMIT 100', w.id);
    const recordings = db.all(
      `SELECT id, owner_id, bytes, mime, created, shared, CASE WHEN owner_id = ? OR shared = 1 THEN transcript ELSE '' END AS transcript
       FROM meeting_recordings WHERE workspace_id = ? AND (owner_id = ? OR shared = 1) ORDER BY id DESC LIMIT 50`,
      u.id, w.id, u.id,
    ).map((r) => ({ ...r, shared: !!r.shared, mine: r.owner_id === u.id }));
    const reports = db.all('SELECT id, owner_id, recording_id, report, source, created FROM meeting_reports WHERE workspace_id = ? AND owner_id = ? ORDER BY id DESC LIMIT 30', w.id, u.id);
    const messages = db.all('SELECT id, role, content, created FROM ai_chats WHERE workspace_id = ? AND user_id = ? ORDER BY id DESC LIMIT 30', w.id, u.id).reverse();
    const members = db.all('SELECT u.id, u.name, u.role FROM workspace_members wm JOIN users u ON wm.user_id = u.id WHERE wm.workspace_id = ? ORDER BY u.name', w.id);
    const activeRecorders = db.get('SELECT COUNT(*) total FROM recording_signals WHERE workspace_id = ? AND started > ?', w.id, Date.now() - 4 * 3_600_000).total;
    const course = w.course_id ? db.get('SELECT id, code, title FROM courses WHERE id = ?', w.course_id) : null;
    return {
      room: { ...w, live: !!w.live, isOwner: w.creator_id === u.id, canGuide: access.teachesWorkspace(u, w), course },
      notes, recordings, reports, messages, members, activeRecorders,
      ...ai.status(u),
    };
  });

  router.patch('/api/workspaces/:id', async (ctx) => {
    const w = access.workspaceOwner(ctx.user, id(ctx.params.id));
    if (!w) throw forbidden('Only the space owner can change its settings');
    const b = await ctx.json();
    const title = text(b.title, { min: 3, max: 120, label: 'Title' });
    const guidance = oneOf(b.guidance, GUIDANCE, 'Assistant approach');
    const instructions = text(b.instructions, { max: 2000, optional: true });
    db.run('UPDATE workspaces SET title = ?, guidance = ?, instructions = ? WHERE id = ?', title, guidance, instructions, w.id);
    touch(w, 'settings');
    return { ok: true };
  });

  router.post('/api/workspaces/:id/leave', (ctx) => {
    const w = member(ctx.user, ctx.params.id);
    if (w.creator_id === ctx.user.id) throw badRequest('Owners cannot leave their own space. Archive it instead.');
    db.run('DELETE FROM workspace_members WHERE workspace_id = ? AND user_id = ?', w.id, ctx.user.id);
    touch(w, 'members');
    return { ok: true };
  });

  router.post('/api/workspaces/:id/archive', (ctx) => {
    const w = access.workspaceOwner(ctx.user, id(ctx.params.id));
    if (!w) throw forbidden('Only the owner can archive this space');
    db.run('UPDATE workspaces SET archived = 1 WHERE id = ?', w.id);
    return { ok: true };
  });

  router.post('/api/workspaces/:id/notes', async (ctx) => {
    const w = member(ctx.user, ctx.params.id);
    const b = await ctx.json();
    const category = oneOf(b.category, NOTE_TYPES, 'Note type');
    const content = text(b.content, { min: 3, max: 10_000, label: 'Note' });
    const noteId = db.insert('INSERT INTO workspace_notes(workspace_id, author_id, category, content, created) VALUES(?, ?, ?, ?, ?)', w.id, ctx.user.id, category, content, isoNow());
    touch(w, 'notes');
    ctx.status = 201;
    return { id: noteId };
  });

  router.delete('/api/workspaces/:id/notes/:noteId', (ctx) => {
    const w = member(ctx.user, ctx.params.id);
    const note = db.get('SELECT * FROM workspace_notes WHERE id = ? AND workspace_id = ?', id(ctx.params.noteId), w.id);
    if (!note) throw notFound('Note not found');
    if (note.author_id !== ctx.user.id && w.creator_id !== ctx.user.id) throw forbidden('Only the author or the space owner can delete this note');
    db.run('DELETE FROM workspace_notes WHERE id = ?', note.id);
    touch(w, 'notes');
    return { ok: true };
  });

  // --- Workspace assistant (guidance-aware) ---

  function workspaceSystem(user, w, question) {
    const notes = db.all('SELECT category, content FROM workspace_notes WHERE workspace_id = ? ORDER BY id DESC LIMIT 25', w.id).reverse().map((x) => `[${x.category}] ${x.content}`).join('\n').slice(0, 8500);
    const { references } = ai.retrieveContext(user, `${w.title} ${question}`);
    return prompts.workspacePrompt({ user, workspace: w, sources: references, notes });
  }

  router.post('/api/workspaces/:id/assistant', async (ctx) => {
    const w = member(ctx.user, ctx.params.id);
    const b = await ctx.json();
    const prompt = text(b.prompt, { min: 2, max: 2000, label: 'Question' });
    if (!ai.status(ctx.user).aiEnabled) throw unavailable('AI is not configured. An administrator can choose a provider in AI & knowledge.');
    const history = db.all('SELECT role, content FROM ai_chats WHERE workspace_id = ? AND user_id = ? ORDER BY id DESC LIMIT 8', w.id, ctx.user.id).reverse();
    const answer = await ai.complete({ user: ctx.user, system: workspaceSystem(ctx.user, w, prompt), prompt, history });
    db.run('INSERT INTO ai_chats(workspace_id, user_id, role, content, created) VALUES(?, ?, ?, ?, ?)', w.id, ctx.user.id, 'user', prompt, isoNow());
    db.run('INSERT INTO ai_chats(workspace_id, user_id, role, content, created) VALUES(?, ?, ?, ?, ?)', w.id, ctx.user.id, 'assistant', answer, isoNow());
    return { answer };
  });

  router.delete('/api/workspaces/:id/assistant', (ctx) => {
    const w = member(ctx.user, ctx.params.id);
    db.run('DELETE FROM ai_chats WHERE workspace_id = ? AND user_id = ?', w.id, ctx.user.id);
    return { ok: true };
  });

  // --- Meeting minutes ---

  router.post('/api/workspaces/:id/analyze', async (ctx) => {
    const w = member(ctx.user, ctx.params.id);
    const b = await ctx.json();
    const recordingId = optionalId(b.recording_id, 'Recording');
    let source = db.all("SELECT content FROM workspace_notes WHERE workspace_id = ? AND category IN ('note','minutes','task') ORDER BY id LIMIT 90", w.id).map((n) => n.content).join('\n');
    if (b.include_captions) source += '\n' + db.all('SELECT text FROM live_captions WHERE workspace_id = ? ORDER BY id', w.id).map((c) => c.text).join(' ');
    if (recordingId) {
      const rec = recordingFor(ctx.user, recordingId);
      if (!rec || rec.workspace_id !== w.id || rec.owner_id !== ctx.user.id) throw forbidden('Only the person who recorded this can analyse it');
      source += '\n' + rec.transcript;
    }
    source = source.slice(0, 40_000);
    if (!source.trim()) throw badRequest('Add meeting notes or a transcript first');
    const useAi = ai.status(ctx.user).aiEnabled;
    const report = useAi ? await ai.complete({ user: ctx.user, system: prompts.meetingPrompt(w.title), prompt: prompts.referenceBlock('NOTES', source.slice(0, 20_000)), maxTokens: 1500, task: 'summary' }) : offlineMinutes(source);
    const label = useAi ? 'AI draft' : 'Offline extraction';
    const reportId = db.insert('INSERT INTO meeting_reports(workspace_id, owner_id, recording_id, report, source, created) VALUES(?, ?, ?, ?, ?, ?)', w.id, ctx.user.id, recordingId, report, label, isoNow());
    return { id: reportId, report, source: label };
  });

  router.delete('/api/workspaces/:id/reports/:reportId', (ctx) => {
    const w = member(ctx.user, ctx.params.id);
    db.run('DELETE FROM meeting_reports WHERE id = ? AND workspace_id = ? AND owner_id = ?', id(ctx.params.reportId), w.id, ctx.user.id);
    return { ok: true };
  });

  // --- Recordings (private to the recorder unless shared) ---

  router.post('/api/workspaces/:id/recording-signal', async (ctx) => {
    const w = member(ctx.user, ctx.params.id);
    const b = await ctx.json();
    if (b.active) db.run('INSERT INTO recording_signals(workspace_id, user_id, started) VALUES(?, ?, ?) ON CONFLICT(workspace_id, user_id) DO UPDATE SET started = excluded.started', w.id, ctx.user.id, Date.now());
    else db.run('DELETE FROM recording_signals WHERE workspace_id = ? AND user_id = ?', w.id, ctx.user.id);
    touch(w, 'recording');
    return { ok: true };
  });

  router.post('/api/workspaces/:id/recordings', async (ctx) => {
    const w = member(ctx.user, ctx.params.id);
    const mime = String(ctx.req.headers['content-type'] || '').split(';')[0].trim();
    if (!AUDIO_TYPES[mime]) {
      ctx.status = 415;
      return { error: 'Unsupported recording format' };
    }
    const buffer = await ctx.raw(18 * 1024 * 1024);
    if (!buffer.length) throw badRequest('The recording is empty');
    const filename = crypto.randomUUID() + AUDIO_TYPES[mime];
    fs.writeFileSync(path.join(config.audioDir, filename), buffer, { flag: 'wx', mode: 0o600 });
    const recId = db.insert('INSERT INTO meeting_recordings(workspace_id, owner_id, filename, mime, bytes, created) VALUES(?, ?, ?, ?, ?, ?)', w.id, ctx.user.id, filename, mime, buffer.length, isoNow());
    let transcript = '';
    let warning = '';
    if (ai.transcriptionReady()) {
      try {
        transcript = await ai.transcribe({ user: ctx.user, buffer, mime });
        if (transcript) db.run('UPDATE meeting_recordings SET transcript = ? WHERE id = ?', transcript, recId);
        else warning = 'Audio saved, but automatic transcription returned nothing.';
      } catch {
        warning = 'Audio saved, but automatic transcription failed.';
      }
    }
    ctx.status = 201;
    return { id: recId, transcript, warning, ...ai.status(ctx.user) };
  });

  router.get('/api/workspaces/recordings/:id/audio', (ctx) => {
    const rec = recordingFor(ctx.user, ctx.params.id);
    if (!rec || !access.workspaceMember(ctx.user, rec.workspace_id) || (rec.owner_id !== ctx.user.id && !rec.shared)) throw forbidden('This recording is private');
    const file = path.join(config.audioDir, rec.filename);
    let stat;
    try {
      stat = fs.statSync(file);
    } catch {
      throw notFound('Audio file missing');
    }
    ctx.res.writeHead(200, {
      'Content-Type': rec.mime,
      'Content-Length': stat.size,
      'Content-Disposition': `${ctx.query.get('download') ? 'attachment' : 'inline'}; filename="campusos-meeting-${rec.id}${path.extname(rec.filename)}"`,
      'Cache-Control': 'no-store',
    });
    fs.createReadStream(file).pipe(ctx.res);
  });

  router.patch('/api/workspaces/recordings/:id', async (ctx) => {
    const rec = recordingFor(ctx.user, ctx.params.id);
    if (!rec || rec.owner_id !== ctx.user.id) throw forbidden('Only the person who recorded this can edit it');
    const b = await ctx.json();
    if (b.shared !== undefined) db.run('UPDATE meeting_recordings SET shared = ? WHERE id = ?', b.shared === true ? 1 : 0, rec.id);
    if (typeof b.transcript === 'string') db.run('UPDATE meeting_recordings SET transcript = ? WHERE id = ?', b.transcript.trim().slice(0, 100_000), rec.id);
    return { ok: true };
  });

  router.delete('/api/workspaces/recordings/:id', (ctx) => {
    const rec = recordingFor(ctx.user, ctx.params.id);
    if (!rec || rec.owner_id !== ctx.user.id) throw forbidden('Only the person who recorded this can delete it');
    db.run('DELETE FROM meeting_reports WHERE recording_id = ?', rec.id);
    db.run('DELETE FROM meeting_recordings WHERE id = ?', rec.id);
    try {
      fs.unlinkSync(path.join(config.audioDir, rec.filename));
    } catch {
      /* already gone */
    }
    return { ok: true };
  });

  // --- Live captions ---

  router.post('/api/workspaces/:id/live', async (ctx) => {
    const w = member(ctx.user, ctx.params.id);
    if (!access.teachesWorkspace(ctx.user, w) && w.creator_id !== ctx.user.id) throw forbidden('Only the lecturer or space owner can start live captions');
    const b = await ctx.json();
    db.run('UPDATE workspaces SET live = ? WHERE id = ?', b.active ? 1 : 0, w.id);
    if (b.active && b.reset) db.run('DELETE FROM live_captions WHERE workspace_id = ?', w.id);
    bus.publish(`workspace:${w.id}`, 'captions.state', { workspaceId: w.id, live: !!b.active });
    return { ok: true, live: !!b.active };
  });

  router.post('/api/workspaces/:id/captions', async (ctx) => {
    const w = member(ctx.user, ctx.params.id);
    if (!w.live) throw badRequest('Live captions are not running');
    if (!access.teachesWorkspace(ctx.user, w) && w.creator_id !== ctx.user.id) throw forbidden('Only the speaker can add captions');
    const b = await ctx.json();
    const line = text(b.text, { min: 1, max: 1000, label: 'Caption' });
    const captionId = db.insert('INSERT INTO live_captions(workspace_id, author_id, text, created) VALUES(?, ?, ?, ?)', w.id, ctx.user.id, line, isoNow());
    bus.publish(`workspace:${w.id}`, 'caption', { workspaceId: w.id, id: captionId, text: line });
    return { id: captionId };
  });

  router.get('/api/workspaces/:id/captions', (ctx) => {
    const w = member(ctx.user, ctx.params.id);
    const after = Number(ctx.query.get('after') || 0);
    return { live: !!w.live, captions: db.all('SELECT id, text, created FROM live_captions WHERE workspace_id = ? AND id > ? ORDER BY id LIMIT 500', w.id, after) };
  });

  router.post('/api/workspaces/:id/captions/summary', async (ctx) => {
    const w = member(ctx.user, ctx.params.id);
    const transcript = db.all('SELECT text FROM live_captions WHERE workspace_id = ? ORDER BY id', w.id).map((c) => c.text).join(' ').slice(-20_000);
    if (transcript.length < 40) throw badRequest('There is not enough transcript to summarise yet');
    if (!ai.status(ctx.user).aiEnabled) throw unavailable('AI is not configured');
    const summary = await ai.complete({ user: ctx.user, system: prompts.captionsSummaryPrompt(w.title), prompt: prompts.referenceBlock('TRANSCRIPT', transcript), maxTokens: 800, task: 'summary' });
    return { summary };
  });

  /** Lecturer marks a new topic during a live lecture: adds it to the linked course so students can rate it. */
  router.post('/api/workspaces/:id/topic', async (ctx) => {
    const w = member(ctx.user, ctx.params.id);
    if (!w.course_id || !access.teachingCourse(ctx.user, w.course_id)) throw forbidden('Link this space to one of your courses first');
    const b = await ctx.json();
    const title = text(b.title, { min: 3, max: 160, label: 'Topic' });
    let lecture = db.get("SELECT id FROM lectures WHERE course_id = ? AND status = 'active' ORDER BY id DESC LIMIT 1", w.course_id);
    if (!lecture) lecture = { id: db.insert('INSERT INTO lectures(course_id, topic, created) VALUES(?, ?, ?)', w.course_id, `${w.title} · ${new Date().toLocaleDateString('en-GB')}`, isoNow()) };
    const topicId = db.insert('INSERT INTO topics(lecture_id, title, created) VALUES(?, ?, ?)', lecture.id, title, isoNow());
    bus.publish(`course:${w.course_id}`, 'course.updated', { courseId: w.course_id });
    bus.publish(`workspace:${w.id}`, 'caption', { workspaceId: w.id, id: 0, text: `— New topic: ${title} —`, topic: true });
    audit(ctx.user, 'live_topic_marked', topicId);
    ctx.status = 201;
    return { id: topicId };
  });
}

module.exports = { register, offlineMinutes };
