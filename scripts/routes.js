'use strict';
/**
 * Prints every HTTP route as Markdown (used to generate docs/API.md).
 *   node scripts/routes.js > docs/API.md
 */
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { loadConfig } = require('../src/config');
const { openDatabase } = require('../src/db/database');
const { runMigrations } = require('../src/db/migrate');
const { createApp } = require('../src/app');

const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'campusos-routes-'));
const env = { DB_PATH: path.join(dir, 'routes.db') };
const config = loadConfig(env);
const db = openDatabase(config.dbPath);
runMigrations(db);
const { router } = createApp({ config, db, env });

const groups = new Map();
for (const r of router.routes) {
  const key = r.pattern.startsWith('/api/') ? r.pattern.split('/')[r.pattern.startsWith('/api/v1/') ? 3 : 2] : r.pattern.split('/')[1];
  if (!groups.has(key)) groups.set(key, []);
  groups.get(key).push(r);
}

const lines = [
  '# HTTP API',
  '',
  'Generated by `node scripts/routes.js`. All `/api/*` routes are also served under `/api/v1/*`.',
  'Responses are JSON; errors are `{ "error": "message" }` with a meaningful status code.',
  'Auth: **user** = session cookie required · **public** = optional · **device** = signed device request (see HARDWARE.md).',
  'State-changing browser requests must be same-origin (CSRF protection).',
  '',
];
for (const [group, routes] of [...groups.entries()].sort()) {
  lines.push(`## ${group}`, '', '| Method | Path | Auth | Roles |', '|---|---|---|---|');
  for (const r of routes) lines.push(`| ${r.method} | \`${r.pattern}\` | ${r.options.auth || 'user'} | ${(r.options.roles || []).join(', ') || 'any'} |`);
  lines.push('');
}
process.stdout.write(lines.join('\n'));
db.close();
fs.rmSync(dir, { recursive: true, force: true });
